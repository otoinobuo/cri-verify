"""Generate lean/CrossCheck.lean: 60 random (base, reference) pairs (seed 20261029) whose results the Python model
computes and the Lean definitions re-check by `decide`.  Run: python3 model/gen_crosscheck.py"""
import sys, random, os
sys.path.insert(0, os.path.dirname(__file__))
from cri import *
import check, seglevel
random.seed(20261029)
SEGMAP = {'a': 'A', 'b': 'B', '': '.empty', 'x:y': 'X', '.': '.dot', '..': '.dotdot'}
def lseg(s): return SEGMAP[s]
def llist(l): return '[' + ', '.join(l) + ']'
def lpath(p): return llist([lseg(s) for s in p])
def lq(q): return llist(['7' for _ in q])
def lopt(x): return 'none' if x is None else 'some %s' % x
def ldisc(d): return '.all' if d is True else '.n %d' % d
bases = [b for b in check.bases() if isinstance(b['authority'], tuple)]
refs = [r for r in check.refs() if r['discard'] is not None]
pairs = random.sample([(b, r) for b in bases for r in refs], 60)
out = ['import Cri', '', '/-! 60 random cases (seed 20261029) computed by the Python model (model/cri.py, model/seglevel.py) and re-checked here by `decide`. Generated by model/gen_crosscheck.py. -/', '', 'def X : Seg := .other 3 true', '']
for b, r in pairs:
    lb = '⟨%s, %s⟩' % (lpath(b['path']), lq(b['query']))
    lr = '⟨%s, %s, %s, %s⟩' % (ldisc(r['discard']), lopt(lpath(r['path'])) if r['path'] is not None else 'none',
                                lopt(lq(r['query'])) if r['query'] is not None else 'none', lopt('9') if r['fragment'] is not None else 'none')
    rr = resolve(b, r)
    lt = '⟨%s, %s, %s⟩' % (lpath(rr['path']), lq(rr['query']), lopt('9') if rr['fragment'] is not None else 'none')
    out.append('example : resolveCRI %s %s = %s := by decide' % (lb, lr, lt))
    for fixed, name in ((False, 'convDraft'), (True, 'convFixed')):
        try:
            u = seglevel.uref_of(r, fixed)
            lu = '⟨%s, %s, %s, %s⟩' % ('true' if u['rooted'] else 'false', lopt(lpath(u['segs'])) if u['segs'] is not None else 'none',
                                        lopt(lq(u['query'])) if u['query'] is not None else 'none', lopt('9') if u['fragment'] is not None else 'none')
            out.append('example : %s %s = some %s := by decide' % (name, lr, lu))
            tp, tq, tf = seglevel.resolve_segs(b, u)
            lt2 = '⟨%s, %s, %s⟩' % (lpath(tp), lq(tq if tq is not None else []), lopt('9') if tf is not None else 'none')
            out.append('example : resolve3986 %s %s = %s := by decide' % (lb, lu, lt2))
        except ConversionFails:
            out.append('example : %s %s = none := by decide' % (name, lr))
open(os.path.join(os.path.dirname(__file__), '..', 'lean', 'CrossCheck.lean'), 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
